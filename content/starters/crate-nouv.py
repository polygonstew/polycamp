crate.data.materials.append(kit.pbr('Crate', (0.6, 0.45, 0.3, 1), roughness=0.7))
kit.add_light('AREA', 'Key', (3, -4, 5), 400, (1, 0.95, 0.9), size=3, collection=get_collection('Lights'))
