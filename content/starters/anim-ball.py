# A ball, a floor and a camera. Nothing is animated yet.
kit.wipe()
kit.reset_scene_settings()
kit.make_world((0.1, 0.11, 0.14, 1), 1.0)
col = get_collection('Stage')
bm = bmesh.new()
kit.add_sphere(bm, 0.5, 32, 16)
ball = kit.mesh_object('Ball', bm, collection=col, loc=(-3, 0, 0.5), smooth=True)
ball.data.materials.append(kit.pbr('Ball', (0.85, 0.2, 0.15, 1), roughness=0.35))
bm = bmesh.new()
box_at(bm, (10, 4, 0.1), (0, 0, -0.05))
floor = kit.mesh_object('Floor', bm, collection=col)
floor.data.materials.append(kit.pbr('Floor', (0.4, 0.42, 0.48, 1), roughness=0.8))
kit.add_light('AREA', 'Key', (2, -5, 5), 500, (1, 0.95, 0.9), size=4, collection=get_collection('Lights'))
kit.look_at(bpy.data.objects['Key'], (0, 0, 0.5))
kit.add_camera('Camera', (0, -9, 2.2), (0, 0, 1.0), 40, get_collection('Lights'))
kit.select_only(ball)
