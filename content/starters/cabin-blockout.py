# A plain cabin blockout: a wall box and a flat roof slab on a ground disc. The lesson turns it into a real shell.
kit.wipe()
kit.reset_scene_settings()
kit.make_world()
col = get_collection('Cabin')
bm = bmesh.new()
box_at(bm, (3.6, 2.8, 2.1), (0, 0, 1.05))
walls = kit.mesh_object('Walls', bm, collection=col)
walls.data.materials.append(mat_wood('Cabin_Wood', '#a8723e', '#4f2f16', 9.0))
bm = bmesh.new()
box_at(bm, (4.4, 3.6, 0.5), (0, 0, 2.35))
roof = kit.mesh_object('Roof', bm, collection=col)
roof.data.materials.append(mat_roof())
bm = bmesh.new()
kit.add_cylinder(bm, 4.0, 0.2, 48, center=(0, 0, -0.1))
ground = kit.mesh_object('Ground', bm, collection=get_collection('Ground'), smooth=True)
ground.data.materials.append(mat_grass())
kit.add_light('SUN', 'Sun', (-5, -6, 6), 3.0, (1.0, 0.85, 0.65), size=3, collection=get_collection('Lights'))
kit.look_at(bpy.data.objects['Sun'], (0, 0, 0))
kit.add_camera('Camera', (7.5, -9.0, 4.5), (0, 0, 1.4), 38, get_collection('Lights'))
kit.select_only(roof)
