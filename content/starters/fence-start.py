# One fence post and one rail on a plain ground, for the duplicates and instances lesson.
kit.wipe()
kit.reset_scene_settings()
kit.make_world()
col = get_collection('Fence')
wood = mat_wood('Fence_Wood', '#9a6a3c', '#4a2d16', 5.0)
bm = bmesh.new()
box_at(bm, (0.1, 0.1, 0.95), (0, 0, 0.475))
post = kit.mesh_object('Post', bm, collection=col, loc=(-3, 0, 0))
post.data.materials.append(wood)
add_bevel(post, 0.012)
bm = bmesh.new()
box_at(bm, (1.5, 0.05, 0.08))
rail = kit.mesh_object('Rail', bm, collection=col, loc=(-2.25, 0, 0.7))
rail.data.materials.append(wood)
bm = bmesh.new()
box_at(bm, (10, 6, 0.1), (0, 0, -0.05))
ground = kit.mesh_object('Ground', bm, collection=get_collection('Ground'))
ground.data.materials.append(mat_grass())
kit.add_light('SUN', 'Sun', (-5, -6, 6), 3.0, (1.0, 0.85, 0.65), size=3, collection=get_collection('Lights'))
kit.look_at(bpy.data.objects['Sun'], (0, 0, 0))
kit.add_camera('Camera', (0, -9, 3.5), (0, 0, 0.6), 38, get_collection('Lights'))
kit.select_only(post)
