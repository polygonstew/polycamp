# Three spheres on a floor, all sharing one plain grey material: a test bench for materials.
kit.wipe()
kit.reset_scene_settings()
kit.make_world((0.12, 0.13, 0.16, 1), 1.0)
col = get_collection('Bench')
grey = kit.pbr('Grey', (0.8, 0.8, 0.8, 1), roughness=0.5)
for name, x in (('Sphere_A', -2.2), ('Sphere_B', 0.0), ('Sphere_C', 2.2)):
    bm = bmesh.new()
    kit.add_sphere(bm, 0.9, 48, 24)
    ob = kit.mesh_object(name, bm, collection=col, loc=(x, 0, 0.9), smooth=True)
    ob.data.materials.append(grey)
bm = bmesh.new()
box_at(bm, (9, 5, 0.1), (0, 0, -0.05))
floor = kit.mesh_object('Floor', bm, collection=col)
floor.data.materials.append(kit.pbr('Floor', (0.35, 0.36, 0.4, 1), roughness=0.8))
kit.add_light('AREA', 'Key', (2.5, -4, 4.5), 400, (1, 0.95, 0.9), size=3, collection=get_collection('Lights'))
kit.look_at(bpy.data.objects['Key'], (0, 0, 0.8))
kit.add_light('AREA', 'Rim', (-4, 3, 3), 150, (0.7, 0.8, 1.0), size=3, collection=get_collection('Lights'))
kit.look_at(bpy.data.objects['Rim'], (0, 0, 0.8))
kit.add_camera('Camera', (0, -7.5, 2.4), (0, 0, 0.9), 45, get_collection('Lights'))
kit.select_only(bpy.data.objects['Sphere_A'])
